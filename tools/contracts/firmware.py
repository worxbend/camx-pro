"""Generate or check the small mechanical contract used by ESP32 firmware."""
import argparse
import json
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "firmware/include/camx/mechanics.hpp"


def content():
    p = json.loads((ROOT / "hardware/cad/parameters.json").read_text())
    values = {
        "motorSteps": p["motor"]["half_steps_per_turn"],
        "panReduction": 1 + p["pan"]["ring_teeth"] / p["pan"]["sun_teeth"],
        "tiltReduction": p["tilt"]["axis_teeth"] / p["tilt"]["motor_teeth"],
        "panMinimum": p["pan"]["minimum"], "panMaximum": p["pan"]["maximum"],
        "tiltMinimum": p["tilt"]["minimum"], "tiltMaximum": p["tilt"]["maximum"],
        "panSpeed": p["motion"]["pan_speed"], "tiltSpeed": p["motion"]["tilt_speed"],
        "acceleration": p["motion"]["acceleration"], "maxStepRate": p["motion"]["maximum_step_rate"],
    }
    fingerprint = zlib.crc32(json.dumps(values, sort_keys=True).encode())
    return ("// Generated by tools/contracts/firmware.py from hardware/cad/parameters.json.\n"
            "#pragma once\n#include <cstdint>\nnamespace camx::mechanics {\n" +
            "".join(f"inline constexpr double {key} = {value:.12g};\n" for key, value in values.items()) +
            f"inline constexpr uint32_t fingerprint = {fingerprint}u;\n" + "}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = content()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("Mechanical contract is stale. Run tools/contracts/firmware.py and review changes.")
        print("Firmware/CAD mechanical contract: PASS")
    else:
        TARGET.write_text(expected)
